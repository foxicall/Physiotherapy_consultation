"""Build the offline catalog and content-versioned service worker."""
import hashlib
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
runpy.run_path(str(ROOT/'scripts'/'build_catalog.py'), run_name='__main__')
ASSETS = ['index.html','styles.css','app.mjs','lib.mjs','catalog.json','config.json','manifest.webmanifest','icons/icon-192.png','icons/icon-512.png','icons/maskable-512.png','icons/apple-touch-icon.png']
digest = hashlib.sha256()
for asset in ASSETS:
    digest.update(asset.encode())
    digest.update((ROOT/'docs'/asset).read_bytes())
version = digest.hexdigest()[:16]
worker = r'''// Generated by scripts/build_pwa.py; version changes with the offline assets.
const PREFIX = 'pt-clinic-' + encodeURIComponent(self.registration.scope) + '-';
const CACHE = PREFIX + '__VERSION__';
const ASSETS = __ASSETS__;
const urls = ASSETS.map(path => new URL(path, self.registration.scope).href);
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(urls)));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) if (name.startsWith(PREFIX) && name !== CACHE) await caches.delete(name);
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
});
self.addEventListener('fetch', event => {
  const request = event.request, url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(self.registration.scope)) return;
  // Never intercept API requests, session tokens, or generated conversation content.
  const relative = url.pathname.slice(new URL(self.registration.scope).pathname.length);
  if (relative.startsWith('api/')) return;
  if (request.mode === 'navigate' && (relative === '' || relative === 'index.html')) {
    event.respondWith((async () => {
      // Keep HTML and scripts from the same release until the user accepts an update.
      const cached = await (await caches.open(CACHE)).match(new URL('index.html', self.registration.scope).href);
      return cached || fetch(request);
    })());
  } else if (urls.includes(url.href)) {
    // The immutable cache belongs to one release; a waiting worker holds updates.
    event.respondWith((async () => (await (await caches.open(CACHE)).match(request)) || fetch(request))());
  }
});
'''
import json
worker = worker.replace('__VERSION__', version).replace('__ASSETS__', json.dumps(ASSETS))
(ROOT/'docs'/'sw.js').write_text(worker, encoding='utf-8')
print('Built offline app:', version)
